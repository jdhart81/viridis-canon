#!/usr/bin/env bash
# Auto-intake step for the viridis-engine nightly job (docs/auto_intake/README.md).
#
# Runs inside the existing nightly job after the run is certified; adds no schedule (AI-8).
# Needs: CANON (viridis-canon checkout), VIRIDISOS (viridisos checkout), RESEARCH (viridis-research
# checkout), GH_TOKEN with contents and pull-request write on viridis-canon and viridisos, and
# DRAFT, a command that runs the engine's Claude on docs/auto_intake/DRAFTING.md for the statement
# in $STATEMENT and writes research/<id>/ (or records a decline).
#
# Order each night:
#   A sweep: merge open auto-intake PRs whose checks are all green; report red ones (AI-4)
#   B refresh ViridisOS from canon main if its auto-kernel list is stale (AI-5)
#   C plan; draft at most one candidate; verify, apply, go-live, gates; open the PR (AI-1..AI-3, AI-6)
#   D print the owner's note for the kernel-flag email (AI-7)
set -euo pipefail
: "${CANON:?}" "${VIRIDISOS:?}" "${RESEARCH:?}"
INDEX="$RESEARCH/index/certified.json"
SINCE="${SINCE:-$(date -u -d '1 day ago' +%Y-%m-%dT%H:%M:%SZ)}"
log() { echo "auto-intake: $*"; }

# A. sweep: merge only green PRs ---------------------------------------------------------
for repo in jdhart81/viridis-canon jdhart81/viridisos; do
  for pr in $(gh pr list -R "$repo" --state open --search "head:auto-intake/" --json number -q '.[].number'); do
    states=$(gh pr checks "$pr" -R "$repo" --json state -q '[.[].state | select(. != "SKIPPED" and . != "NEUTRAL")] | unique | join(",")' || echo "UNKNOWN")
    if [ "$states" = "SUCCESS" ]; then
      gh pr merge "$pr" -R "$repo" --squash --delete-branch && log "merged $repo#$pr"
    elif echo "$states" | grep -qE 'FAILURE|ERROR|CANCELLED'; then
      log "left open $repo#$pr: checks $states"
    else
      log "waiting on $repo#$pr: checks $states"
    fi
  done
done

# B. ViridisOS follows canon main --------------------------------------------------------
git -C "$CANON" fetch -q origin main && git -C "$CANON" checkout -q --detach origin/main
if ! (cd "$VIRIDISOS" && python3 tools/refresh_from_canon.py --canon "$CANON" --check >/dev/null); then
  branch="auto-intake/os-refresh-$(git -C "$CANON" rev-parse --short HEAD)"
  ( cd "$VIRIDISOS" && git fetch -q origin main && git checkout -q -B "$branch" origin/main \
    && python3 tools/refresh_from_canon.py --canon "$CANON" && bash run_all_tests.sh >/dev/null \
    && git add runtime/canon_auto_kernels.json \
    && git commit -s -qm "runtime: refresh auto-intake kernels from canon $(git -C "$CANON" rev-parse --short HEAD)" \
    && git push -q -u origin "$branch" \
    && gh pr create -R jdhart81/viridisos --head "$branch" --title "Auto-intake: refresh kernels from canon" \
         --body "Generated by tools/auto_intake/engine_step.sh from canon $(git -C "$CANON" rev-parse HEAD). Merges when its checks pass." ) \
    && log "opened ViridisOS refresh $branch" || log "ViridisOS refresh failed; left for review"
fi

# C. one candidate per night -------------------------------------------------------------
STATEMENT=$(cd "$CANON" && python3 -m canon_core auto-intake plan --index "$INDEX" --research-root "$RESEARCH" \
  | python3 -c 'import json,sys; c=json.load(sys.stdin)["candidates"]; print(c[0] if c else "")')
if [ -n "$STATEMENT" ] && ! gh pr list -R jdhart81/viridis-canon --state open --search "head:auto-intake/$STATEMENT" --json number -q '.[0].number' | grep -q .; then
  branch="auto-intake/$STATEMENT"
  cd "$CANON" && git checkout -q -B "$branch" origin/main
  export STATEMENT INDEX RESEARCH
  if ! $DRAFT; then log "draft for $STATEMENT failed; nothing kept"; git reset -q --hard && git clean -qfd; fi
  pkg=$(git status --porcelain --untracked-files=all | awk '{print $2}' | grep -oE '^research/[a-z0-9-]+/' | sort -u | head -1 || true)
  if [ -n "$pkg" ]; then
    if python3 -m canon_core auto-intake verify --index "$INDEX" --research-root "$RESEARCH" --package "$pkg" \
       && python3 -m canon_core auto-intake apply --index "$INDEX" --research-root "$RESEARCH" --package "$pkg" >/dev/null \
       && { [ "$(python3 -c 'import json;print(json.load(open("os/auto_intake.json"))["go_live"])')" != "True" ] \
            || python3 -m canon_core auto-intake go-live --function "$(basename "$pkg")" >/dev/null; } \
       && python3 -m canon_core validate-functions \
       && python3 -m canon_core build-os --out "$(mktemp -d)/os-bundle" \
       && python3 tools/build_formalization_yaml.py --check && python3 tools/build_certificates_index.py --check \
       && python3 -m unittest discover -s tests -q; then
      git add -A && git commit -s -qm "auto-intake: $STATEMENT enters as $(basename "$pkg")" \
        && git push -q -u origin "$branch" \
        && gh pr create -R jdhart81/viridis-canon --head "$branch" --title "Auto-intake: $STATEMENT → $(basename "$pkg")" \
             --body "$(python3 -m canon_core auto-intake note --since "$SINCE")
Generated by tools/auto_intake/engine_step.sh. Merges automatically when canon CI is green (owner decision 2026-11-17)." \
        && log "opened PR for $STATEMENT"
    else
      log "$STATEMENT did not pass the gates; nothing kept"; git reset -q --hard && git clean -qfd
    fi
  elif ! git diff --quiet -- os/research_statements.json; then
    git add os/research_statements.json && git commit -s -qm "auto-intake: record $STATEMENT as not entered" \
      && git push -q -u origin "$branch" \
      && gh pr create -R jdhart81/viridis-canon --head "$branch" --title "Auto-intake: $STATEMENT not entered" \
           --body "$(python3 -m canon_core auto-intake note --since "$SINCE")" && log "recorded decline for $STATEMENT"
  fi
fi

# D. owner note ------------------------------------------------------------------------------
cd "$CANON" && git checkout -q --detach origin/main && python3 -m canon_core auto-intake note --since "$SINCE"
