#!/usr/bin/env python3
"""Build formalization.yaml: machine-readable links between Viridis results and their Lean code.

Standard library only; deterministic. Sources:
    **/function.json          every OS function manifest (result, DOI, Lean module, theorems, verifier)
    certificates/index.json   published Comparator certificates and depth labels

Usage:
    python3 tools/build_formalization_yaml.py          # write formalization.yaml
    python3 tools/build_formalization_yaml.py --check  # exit 1 if it is stale

The file follows the spirit of the Advisory Group on Mathematics and AI's
recommendation (2026-09-29) that formalizations ship with machine-readable links
between natural-language and formal artifacts. Scalars are written as JSON
strings, which are valid YAML.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "formalization.yaml"


def q(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def build() -> str:
    cert_index = json.loads((ROOT / "certificates" / "index.json").read_text())
    by_function: dict[str, dict] = {}
    for run in cert_index["runs"]:
        for fn in run["os_functions"]:
            by_function[fn["id"]] = run

    manifests = []
    for path in sorted(ROOT.glob("**/function.json")):
        if ".lake" in path.parts or "certificates" in path.parts:
            continue
        manifests.append((path, json.loads(path.read_text())))
    manifests.sort(key=lambda pj: pj[1].get("id") or "")

    toolchain = (ROOT / "lean-toolchain").read_text().strip()
    manifest_lock = json.loads((ROOT / "lake-manifest.json").read_text())
    mathlib_rev = next(p["rev"] for p in manifest_lock["packages"] if p["name"] == "mathlib")

    lines = [
        "# formalization.yaml: machine-readable links between Viridis results and their Lean formalizations.",
        "# Generated by tools/build_formalization_yaml.py from os/**/function.json manifests and",
        "# certificates/index.json. Do not edit by hand; edit the manifests and rebuild.",
        "#",
        "# verification.provider:",
        "#   COMPARATOR_CLOUD      main theorems checked by comparator (Lean + nanoda kernels); certificate",
        "#                         published under certificates/ when `certificate` is set",
        "#   CANON_CI_SPINE_BUILD  built with an axiom audit by this repository's CI on every push",
        "#   CANON_PUBLISHED_LEAN  published Lean module that passed the canon gate (see manifest provenance)",
        "#   ARISTOTLE_HISTORICAL  historical Aristotle proof record; not a current Comparator certificate",
        "# empirical_validation is reported exactly as the manifest states it.",
        f"schema: {q('viridis-formalization/1')}",
        f"toolchain: {q(toolchain)}",
        f"mathlib_rev: {q(mathlib_rev)}",
        f"result_count: {len(manifests)}",
        "results:",
    ]
    for path, j in manifests:
        lean = j.get("lean") or {}
        cert = by_function.get(j.get("id"))
        doi = j.get("doi")
        lines += [
            f"  - id: {q(j.get('id'))}",
            f"    title: {q(j.get('name'))}",
            f"    summary: {q(j.get('summary'))}",
            f"    kind: {q(j.get('kind'))}",
            f"    tier: {q(j.get('tier'))}",
            f"    state: {q(j.get('state'))}",
            f"    paper: {q('https://doi.org/' + doi if doi else None)}",
            f"    manifest: {q(str(path.relative_to(ROOT)))}",
            f"    empirical_validation: {q(j.get('empirical_validation'))}",
            "    lean:",
            f"      module: {q(lean.get('module'))}",
            f"      theorems: {q(lean.get('theorems') or [])}",
            "      sources:",
        ]
        for s in lean.get("sources") or []:
            lines.append(f"        - {{path: {q(s.get('path'))}, sha256: {q(s.get('sha256'))}}}")
        if not lean.get("sources"):
            lines[-1] = "      sources: []"
        lines += [
            "    verification:",
            f"      provider: {q(lean.get('verification_provider'))}",
            f"      receipt: {q(lean.get('verification_receipt_id'))}",
            f"      certificate: {q('certificates/' + cert['run'] if cert else None)}",
            f"      depth: {q(cert['depth']['label'] if cert else None)}",
            f"      claim_inventory: {q('certificates/' + cert['run'] + '/' + cert['files']['claim_inventory'] if cert and cert['files'].get('claim_inventory') else None)}",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("formalization.yaml:", "up to date" if ok else "STALE")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('  - id:')} results)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
